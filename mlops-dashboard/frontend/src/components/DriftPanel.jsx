import { useEffect, useState } from "react";
import { api } from "../api";

export default function DriftPanel() {
  const [reports, setReports] = useState(null);
  const [active, setActive] = useState(null);
  const [error, setError] = useState(null);

  useEffect(() => {
    api.driftReports()
      .then((data) => {
        setReports(data);
        if (data.reports.length > 0) setActive(data.reports[0]);
      })
      .catch((e) => setError(e.message));
  }, []);

  return (
    <div>
      <h1 className="page-title">Evidently · Drift Reports</h1>
      <p className="page-sub">HTML reports generated by Drift_report.py / Drift_report_2025vs2026_.py, embedded directly here.</p>

      {error && <div className="error-box">{error}</div>}

      {reports && reports.count === 0 && (
        <div className="empty">No reports found in drift_reports/.</div>
      )}

      {reports && reports.count > 0 && (
        <>
          <div className="report-list">
            {reports.reports.map((r) => (
              <div
                key={r.name}
                className={`report-item ${active?.name === r.name ? "active" : ""}`}
                onClick={() => setActive(r)}
              >
                <span>{r.name}</span>
                <span>{r.modified} · {r.size_kb} KB</span>
              </div>
            ))}
          </div>
          {active && (
            <iframe className="report-frame" src={active.url} title={active.name} />
          )}
        </>
      )}
    </div>
  );
}